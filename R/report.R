## ---------------------------------------------------------------------------
## Release of a sequence: RTF report and CSV.
##
##   Both writers honour `keep.blocks`: when it is FALSE the released artefact
##   contains nothing but the allocation number and the treatment, as required
##   by ICH E9 and good clinical practice.
## ---------------------------------------------------------------------------

#' Write an allocation sequence to an RTF report
#'
#' Produces the deliverable randomization list: the allocation numbers with
#' their treatment (and, optionally, the block structure), followed by the arm
#' balance table. The seed is printed in the report, which therefore has to be
#' handled as confidential trial material (ICH E9 / GCP).
#'
#' @param x An object of class \code{"sandwichrand"}.
#' @param file Path of the RTF file to write.
#' @param title1 Main title of the report.
#' @param title2 Subtitle; \code{NULL} omits the line.
#' @param keep.blocks Logical. Print the block columns. Defaults to the setting
#'   used when the sequence was generated; \code{FALSE} releases a list without
#'   any block information.
#'
#' @return The path \code{file}, invisibly.
#'
#' @examples
#' x <- smr_alloc(N = 12, arms = c("Drug", "Placebo"), seed = 777)
#' f <- tempfile(fileext = ".rtf")
#' smr_rtf(x, f)
#'
#' @export
smr_rtf <- function(x, file,
                    title1 = "The sandwich mixed random-allocation schedule",
                    title2 = NULL,
                    keep.blocks = x$design$keep.blocks) {
    if (!inherits(x, "sandwichrand")) {
        stop("`x` must be an object of class \"sandwichrand\".", call. = FALSE)
    }
    if (!is.character(file) || length(file) != 1L || !nzchar(file)) {
        stop("`file` must be a single non-empty path.", call. = FALSE)
    }
    d <- x$design
    a <- if (isTRUE(keep.blocks)) {
        x$alloc
    } else {
        x$alloc[, c("id", "arm"), drop = FALSE]
    }

    esc <- .smr_rtf_escape
    txt <- c("{\\rtf1\\ansi\\ansicpg1252\\deff0",
             "{\\fonttbl{\\f0\\froman Times New Roman;}{\\f1\\fmodern Courier New;}}",
             "\\viewkind4\\uc1\\pard\\f0\\fs24",
             paste0("\\qc\\b ", esc(sprintf("%s (N=%d)", title1, d$N)),
                    "\\b0\\par"))
    if (!is.null(title2) && nzchar(title2)) {
        txt <- c(txt, paste0("\\qc ", esc(title2), "\\par"))
    }
    txt <- c(txt, "\\par")

    ## ---- allocation list --------------------------------------------------
    txt <- c(txt, "\\pard\\ql\\f1\\fs18")
    if (all(c("block", "block_size") %in% names(a))) {
        txt <- c(txt,
                 esc(sprintf("%-16s%-8s%-14s%s", "Allocation No.", "Block",
                             "Block size", "Treatment")),
                 "\\par")
        for (i in seq_len(nrow(a))) {
            txt <- c(txt,
                     esc(sprintf("%-16d%-8d%-14d%s", a$id[i], a$block[i],
                                 a$block_size[i], as.character(a$arm[i]))),
                     "\\par")
        }
    } else {
        txt <- c(txt,
                 esc(sprintf("%-16s%s", "Allocation No.", "Treatment")),
                 "\\par")
        for (i in seq_len(nrow(a))) {
            txt <- c(txt,
                     esc(sprintf("%-16d%s", a$id[i], as.character(a$arm[i]))),
                     "\\par")
        }
    }

    ## ---- arm balance ------------------------------------------------------
    txt <- c(txt, "\\par\\pard\\qc\\f0\\fs20\\b Treatment frequency\\b0\\par",
             "\\pard\\ql\\f1\\fs18",
             esc(sprintf("%-20s%-14s%-14s%s", "Treatment", "N allocated",
                         "N expected", "Deviation")),
             "\\par")
    for (i in seq_len(nrow(x$balance))) {
        b <- x$balance[i, ]
        txt <- c(txt,
                 esc(sprintf("%-20s%-14d%-14.3f%+.3f",
                             as.character(b$arm), b$n, b$expected,
                             b$deviation)),
                 "\\par")
    }

    ## ---- seed -------------------------------------------------------------
    if (!isTRUE(d$stream_used)) {
        txt <- c(txt, "\\par\\pard\\qc\\f0\\fs20\\b Random seed\\b0\\par",
                 "\\pard\\ql\\f1\\fs18",
                 esc(sprintf("seed = %d  (%s)", d$seed, d$seed_note)),
                 "\\par")
    }

    ## ---- footer -----------------------------------------------------------
    txt <- c(txt, "\\par",
             paste0("\\pard\\qc\\f0\\fs16 ",
                    esc(sprintf("Generated by the R package sandwichrand v%s",
                                .smr_pkg_version())),
                    "\\par", "\\par",
                    "\\qc\\f0\\fs18 This document is confidential (ICH E9/GCP)",
                    "\\par", "}"))

    writeLines(txt, con = file, useBytes = TRUE)
    invisible(file)
}

#' Write an allocation sequence to a CSV file
#'
#' Releases the allocation list as a comma-separated file. The block columns
#' are included only when \code{keep.blocks = TRUE}; otherwise the released
#' file contains only the allocation number and the treatment, as required by
#' ICH E9 and good clinical practice.
#'
#' @param x An object of class \code{"sandwichrand"}.
#' @param file Path of the CSV file to write.
#' @param keep.blocks Logical. Write the block columns. Defaults to the setting
#'   used when the sequence was generated.
#'
#' @return The path \code{file}, invisibly.
#'
#' @examples
#' x <- smr_alloc(N = 12, arms = c("Drug", "Placebo"), seed = 777,
#'                keep.blocks = FALSE)
#' f <- tempfile(fileext = ".csv")
#' smr_write_csv(x, f)
#'
#' @export
smr_write_csv <- function(x, file,
                          keep.blocks = x$design$keep.blocks) {
    if (!inherits(x, "sandwichrand")) {
        stop("`x` must be an object of class \"sandwichrand\".", call. = FALSE)
    }
    if (!is.character(file) || length(file) != 1L || !nzchar(file)) {
        stop("`file` must be a single non-empty path.", call. = FALSE)
    }
    a <- if (isTRUE(keep.blocks)) {
        x$alloc
    } else {
        x$alloc[, c("id", "arm"), drop = FALSE]
    }
    write.csv(a, file = file, row.names = FALSE)
    invisible(file)
}

## Escape the RTF special characters and encode non-ASCII code points.
.smr_rtf_escape <- function(s) {
    if (!length(s)) return(character(0))
    vapply(as.character(s), function(one) {
        if (is.na(one) || !nzchar(one)) return("")
        cp <- utf8ToInt(one)
        if (!length(cp)) return("")
        paste(vapply(cp, function(k) {
            if (k == 92L) "\\\\" else
                if (k == 123L) "\\{" else
                    if (k == 125L) "\\}" else
                        if (k == 10L) "\\line " else
                            if (k < 128L) intToUtf8(k) else sprintf("\\u%d?", k)
        }, character(1)), collapse = "")
    }, character(1), USE.NAMES = FALSE)
}

## Version of the installed package, for the report footer.
.smr_pkg_version <- function() {
    v <- tryCatch(as.character(utils::packageVersion("sandwichrand")),
                  error = function(e) "")
    if (length(v) != 1L || !nzchar(v)) v <- "unknown"
    v
}
